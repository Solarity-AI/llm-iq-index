// Generates data.js from data/models.json and stamps cache-busting versions
// on the page's asset URLs. Run: npm run build
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { pick } from "./pick.mjs";

const root = new URL("../", import.meta.url);
const read = p => readFileSync(new URL(p, root), "utf8");
const db = JSON.parse(read("data/models.json"));


const chosen = pick(db.models);
const q = JSON.stringify;
const M = chosen.map(m => `[${q(m.name)},${q(m.org)},${q(m.type)},${q(m.modes.map(x => [x.mode, x.aa]))},${q(Object.fromEntries(Object.entries(m.trackingai || {}).map(([k, v]) => [k, [v.offline, v.mensa, v.label]])))}]`);
const META = chosen.map(m => `${q(m.name)}:${q([m.aaSlug, m.released, m.params.total, m.params.active, m.params.disclosed ? 1 : 0])}`);

const js = `// GENERATED by scripts/build.mjs from data/models.json. Do not edit by hand.
const UPDATED=${q(db.updated)};
// META: [AA model slug, release (month, per Artificial Analysis), total params, active params (MoE), params disclosed?]
// Closed labs do not publish sizes: those are tier estimates, marked est.
const META={
${META.join(",\n")}
};
const MON=["Jan","Feb","Mar","Apr","May","Jun","Jul","Aug","Sep","Oct","Nov","Dec"];
const rel=n=>{const [y,m]=META[n][1].split("-");return MON[m-1]+" "+y};
const params=n=>{const [,,t,a,d]=META[n];if(!t)return \`<span class="est" title="The lab has not published a parameter count yet">Not published yet</span>\`;return d?\`\${t}\${a?\` <span class="sub">\${a} active</span>\`:\` <span class="sub">dense</span>\`}\`:\`\${t} <span class="est" title="Not disclosed by the lab. Estimate from price, speed and tier relative to open models of known size.">est.</span>\`};
const aaUrl=n=>"https://artificialanalysis.ai/models/"+META[n][0];
const TA="https://www.trackingai.org/home";
// [name, org, type, [[mode, AA index v5]], {mode:[offlineIQ, mensaIQ, TrackingAI label]}]
const M=[
${M.join(",\n")}
];
/** IQ for one mode: 100 + 0.6 × AA index, averaged with TrackingAI offline IQ when that exact mode was tested. */
function iqFor(aa,anchor){const est=100+0.6*aa;return Math.round(anchor?(est+anchor[0])/2:est)}
const rows=[];
for(const [name,org,type,modes,anc] of M)for(const [mode,aa] of modes){
  const a=anc[mode];
  rows.push({name,org,type,mode,aa,a,iq:iqFor(aa,a)});
}
rows.sort((x,y)=>y.iq-x.iq||y.aa-x.aa);
/** Best-scoring mode of each distinct model, highest first. */
const topModels=n=>rows.filter((r,i)=>rows.findIndex(x=>x.name===r.name)===i).slice(0,n);
`;
writeFileSync(new URL("data.js", root), js);

// Cache-busting: a visitor must never get a new page with an old script.
const v = p => createHash("sha256").update(read(p).replaceAll("\r\n", "\n")).digest("hex").slice(0, 8);
let html = read("index.html");
for (const f of ["data.js", "app.js", "fonts.css"]) {
  html = html.replace(new RegExp(`(["'])${f.replace(".", "\\.")}(\\?v=[0-9a-f]+)?\\1`, "g"), `$1${f}?v=${v(f)}$1`);
}
writeFileSync(new URL("index.html", root), html);
console.log(`data.js: ${chosen.length} models, ${chosen.reduce((s, m) => s + m.modes.length, 0)} entries (updated ${db.updated})`);
